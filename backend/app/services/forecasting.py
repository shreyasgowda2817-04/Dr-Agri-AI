import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestRegressor
from datetime import timedelta
from app.core.database import db_instance

class MarketForecastingService:
    MIN_REQUIRED_HISTORY = 30
    
    async def get_historical_data(self, state: str, district: str, market: str, commodity: str):
        db = db_instance.db
        cursor = db["market_prices"].find({
            "state": state,
            "district": district,
            "market": market,
            "commodity": commodity
        }).sort("date", 1) # Sort chronological
        
        records = await cursor.to_list(length=1000)
        return records
        
    def prepare_time_series(self, records):
        df = pd.DataFrame(records)
        if df.empty:
            return df
            
        df['date'] = pd.to_datetime(df['date'])
        df.set_index('date', inplace=True)
        
        # Resample to daily frequency just in case there are missing days, fill forward
        df = df.resample('D').ffill()
        
        # Feature Engineering
        df['price'] = df['modal_price']
        df['lag_1'] = df['price'].shift(1)
        df['lag_3'] = df['price'].shift(3)
        df['lag_7'] = df['price'].shift(7)
        df['rolling_avg_7'] = df['price'].rolling(window=7).mean()
        df['rolling_avg_30'] = df['price'].rolling(window=30).mean()
        
        df['day_of_week'] = df.index.dayofweek
        df['month'] = df.index.month
        
        # Drop NaNs generated by shifting
        df.dropna(inplace=True)
        return df
        
    async def generate_forecast(self, state: str, district: str, market: str, commodity: str, horizon_days: int = 7):
        records = await self.get_historical_data(state, district, market, commodity)
        
        if len(records) < self.MIN_REQUIRED_HISTORY:
            return {
                "predictionAvailable": False,
                "errorCode": "INSUFFICIENT_HISTORY",
                "message": f"Not enough historical data is available to generate a forecast. Found {len(records)} days, need {self.MIN_REQUIRED_HISTORY}."
            }
            
        df = self.prepare_time_series(records)
        if len(df) < self.MIN_REQUIRED_HISTORY:
            return {
                "predictionAvailable": False,
                "errorCode": "INSUFFICIENT_HISTORY",
                "message": "Not enough historical data after cleaning and removing gaps."
            }
            
        # Target variable: price at T+horizon
        df['target'] = df['price'].shift(-horizon_days)
        
        # We can't train on the last 'horizon_days' rows because we don't know their future target yet
        train_df = df.dropna(subset=['target'])
        
        features = ['lag_1', 'lag_3', 'lag_7', 'rolling_avg_7', 'rolling_avg_30', 'day_of_week', 'month']
        
        X_train = train_df[features]
        y_train = train_df['target']
        
        model = RandomForestRegressor(n_estimators=100, random_state=42)
        model.fit(X_train, y_train)
        
        # Now predict for the LAST known day
        latest_row = df.iloc[[-1]]
        X_latest = latest_row[features]
        
        predicted_price = model.predict(X_latest)[0]
        
        # Calculate uncertainty based on rolling standard deviation
        latest_volatility = df['price'].rolling(window=30).std().iloc[-1]
        
        # Historical actuals to send back to frontend
        historical_chart_data = []
        for index, row in df.tail(30).iterrows():
            historical_chart_data.append({
                "date": index.strftime("%b %d"),
                "actual_price": round(row['price']),
                "type": "Historical"
            })
            
        latest_record = records[-1]
        latest_price = latest_record['modal_price']
        
        # Link the last actual to the prediction start to make the line continuous
        future_date = (df.index[-1] + timedelta(days=horizon_days)).strftime("%b %d")
        
        # Also need to seed the prediction start point at the last actual
        historical_chart_data[-1]["predicted_price"] = round(latest_price)
        historical_chart_data[-1]["lower_bound"] = round(latest_price)
        historical_chart_data[-1]["upper_bound"] = round(latest_price)
        
        # Append the future forecast point
        historical_chart_data.append({
            "date": future_date,
            "predicted_price": round(predicted_price),
            "lower_bound": round(predicted_price - (latest_volatility * 0.8)),
            "upper_bound": round(predicted_price + (latest_volatility * 0.8)),
            "type": "Prediction"
        })
        
        return {
            "predictionAvailable": True,
            "crop": commodity,
            "market": market,
            "unit": latest_record.get("unit", "Quintal"),
            "latestMarketPrice": round(latest_price),
            "latestMarketPriceDate": df.index[-1].strftime("%Y-%m-%d"),
            "predictedPrice": round(predicted_price),
            "predictionRange": {
                "low": round(predicted_price - (latest_volatility * 0.8)),
                "high": round(predicted_price + (latest_volatility * 0.8))
            },
            "horizonDays": horizon_days,
            "dataSource": latest_record.get("source", "Official Market Data"),
            "model": "RandomForest-TS",
            "modelVersion": "1.0",
            "historicalObservations": len(records),
            "chart_data": historical_chart_data
        }

forecasting_service = MarketForecastingService()
